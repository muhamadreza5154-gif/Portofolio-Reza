-- ---------------------------------------------------------------------
-- 1. TABEL
-- ---------------------------------------------------------------------

-- Menyimpan role user (admin / user). Dipakai untuk login Dashboard.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'user',
  created_at timestamptz not null default now()
);

-- Daftar project portfolio
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null default '',
  description text default '',
  img text default '',
  tech_stack text[] default '{}',
  features text[] default '{}',
  link text default '',
  github text default '',
  created_at timestamptz not null default now()
);

-- Sertifikat & prestasi (category: 'keahlian' atau 'prestasi')
create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  title text,
  img text not null,
  category text not null default 'keahlian',
  created_at timestamptz not null default now()
);

-- Pengalaman kerja / organisasi
create table if not exists public.experiences (
  id bigint generated by default as identity primary key,
  company text not null default '',
  role text default '',
  year text default '',
  logo text default '',
  order_index integer,
  created_at timestamptz not null default now()
);

-- Galeri foto
create table if not exists public.gallery_photos (
  id bigint generated by default as identity primary key,
  image_url text not null,
  created_at timestamptz not null default now()
);

-- Komentar pengunjung
create table if not exists public.portfolio_comments (
  id bigint generated by default as identity primary key,
  content text not null,
  user_name text not null,
  profile_image text,
  is_pinned boolean not null default false,
  created_at timestamptz not null default now()
);


-- ---------------------------------------------------------------------
-- 2. FUNGSI CEK ADMIN
-- ---------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;


-- ---------------------------------------------------------------------
-- 3. KEAMANAN (Row Level Security)
--    - Semua orang boleh MELIHAT konten.
--    - Hanya ADMIN yang boleh menambah / mengubah / menghapus.
--    - Komentar baru dikirim lewat server (/api/comment) memakai Secret Key.
-- ---------------------------------------------------------------------
alter table public.profiles           enable row level security;
alter table public.projects           enable row level security;
alter table public.certificates       enable row level security;
alter table public.experiences        enable row level security;
alter table public.gallery_photos     enable row level security;
alter table public.portfolio_comments enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles
  for select using (auth.uid() = id);

do $$
declare
  t text;
begin
  foreach t in array array['projects','certificates','experiences','gallery_photos','portfolio_comments'] loop
    execute format('drop policy if exists "public_read" on public.%I', t);
    execute format('create policy "public_read" on public.%I for select using (true)', t);

    execute format('drop policy if exists "admin_insert" on public.%I', t);
    execute format('create policy "admin_insert" on public.%I for insert with check (public.is_admin())', t);

    execute format('drop policy if exists "admin_update" on public.%I', t);
    execute format('create policy "admin_update" on public.%I for update using (public.is_admin()) with check (public.is_admin())', t);

    execute format('drop policy if exists "admin_delete" on public.%I', t);
    execute format('create policy "admin_delete" on public.%I for delete using (public.is_admin())', t);
  end loop;
end $$;


-- ---------------------------------------------------------------------
-- 4. STORAGE (tempat menyimpan gambar)
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public) values
  ('project-images',     'project-images',     true),
  ('certificate-images', 'certificate-images', true),
  ('profile-images',     'profile-images',     true)
on conflict (id) do update set public = true;

-- Admin boleh upload / ubah / hapus gambar project, galeri & sertifikat
drop policy if exists "admin_upload_images" on storage.objects;
create policy "admin_upload_images" on storage.objects
  for insert to authenticated
  with check (bucket_id in ('project-images','certificate-images') and public.is_admin());

drop policy if exists "admin_update_images" on storage.objects;
create policy "admin_update_images" on storage.objects
  for update to authenticated
  using (bucket_id in ('project-images','certificate-images') and public.is_admin());

drop policy if exists "admin_delete_images" on storage.objects;
create policy "admin_delete_images" on storage.objects
  for delete to authenticated
  using (bucket_id in ('project-images','certificate-images','profile-images') and public.is_admin());

-- Pengunjung boleh upload foto profil saat menulis komentar
drop policy if exists "public_upload_avatar" on storage.objects;
create policy "public_upload_avatar" on storage.objects
  for insert to anon, authenticated
  with check (bucket_id = 'profile-images');


-- ---------------------------------------------------------------------
-- 5. REALTIME (komentar baru langsung muncul tanpa refresh)
-- ---------------------------------------------------------------------
do $$
begin
  alter publication supabase_realtime add table public.portfolio_comments;
exception
  when duplicate_object then null;
end $$;


